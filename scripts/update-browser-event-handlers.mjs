#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const REVISION = '3c06821a384385ee5f355148a5fcd427f5230118';
const CAPTURED_AT = '2026-07-31';
const PROFILE_VERSION = 1;
const SOURCE_PATHS = Object.freeze([
  'third_party/blink/renderer/core/dom/element.idl',
  'third_party/blink/renderer/core/frame/window_event_handlers.idl',
  'third_party/blink/renderer/core/fullscreen/element_fullscreen.idl',
  'third_party/blink/renderer/core/html/html_attribute_names.json5',
  'third_party/blink/renderer/core/html/html_element.cc',
  'third_party/blink/renderer/modules/xr/global_event_handlers_onbeforexrselect.idl'
]);
const HTML_SUPPLEMENTS = Object.freeze([
  'onbeforematch', 'onbeforexrselect', 'ontransitioncancel', 'ontransitionrun',
  'ontransitionstart'
]);
const WINDOW_SUPPLEMENTS = Object.freeze([
  'onorientationchange', 'onpagereveal', 'onpageswap'
]);
const REQUIRED_CHROMIUM_HANDLERS = Object.freeze([
  'onbeforecopy', 'onbeforecut', 'onbeforepaste', 'onbeforexrselect',
  'oncontentvisibilityautostatechange', 'onmousewheel', 'onsearch',
  'onwebkitfullscreenchange', 'onwebkitfullscreenerror'
]);

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(projectRoot, 'src/browser-event-handlers.js');

function sortedUnique(values) {
  return [...new Set(values)].sort();
}

async function chromiumSource(sourcePath) {
  const url = `https://chromium.googlesource.com/chromium/src/+/${REVISION}/${sourcePath}?format=TEXT`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Chromium source fetch failed (${response.status}): ${sourcePath}`);
  return Buffer.from(await response.text(), 'base64').toString('utf8');
}

function quotedLines(values) {
  return values.map((value) => `    '${value}'`).join(',\n');
}

function renderProfile(htmlHandlers, windowHandlers) {
  return `// Generated by scripts/update-browser-event-handlers.mjs. Update as one\n// reviewed unit when advancing the browser revision; never resolve HEAD at\n// audit time.\nexport const BROWSER_EVENT_HANDLER_PROFILE =\n  'mvx-chromium-event-handlers-${REVISION.slice(0, 12)}-v${PROFILE_VERSION}';\n\nexport const BROWSER_EVENT_HANDLER_PROVENANCE = Object.freeze({\n  browser: 'Chromium',\n  revision: '${REVISION}',\n  capturedAt: '${CAPTURED_AT}',\n  sources: Object.freeze([\n${quotedLines(SOURCE_PATHS)}\n  ])\n});\n\n// The pinned Chromium HTML attribute registry and trigger table, supplemented\n// by standards-defined handler mixins that the browser implements outside the\n// core table. Window-only names are intentionally kept in the separate list.\nexport const HTML_EVENT_HANDLER_ATTRIBUTES = Object.freeze([\n${quotedLines(htmlHandlers)}\n]);\n\nexport const WINDOW_EVENT_HANDLER_ATTRIBUTES = Object.freeze([\n${quotedLines(windowHandlers)}\n]);\n\nconst HTML_EVENT_HANDLER_SET = new Set(HTML_EVENT_HANDLER_ATTRIBUTES);\nconst WINDOW_EVENT_HANDLER_SET = new Set(WINDOW_EVENT_HANDLER_ATTRIBUTES);\n\nexport function isExecutableHtmlEventHandler(tagName, attributeName) {\n  return HTML_EVENT_HANDLER_SET.has(attributeName)\n    || (['body', 'frameset'].includes(tagName)\n      && WINDOW_EVENT_HANDLER_SET.has(attributeName));\n}\n`;
}

const sources = new Map(await Promise.all(SOURCE_PATHS.map(async (sourcePath) => [
  sourcePath, await chromiumSource(sourcePath)
])));
const registered = [...sources.get(SOURCE_PATHS[3]).matchAll(/^\s+"(on[a-z0-9]+)",$/gm)]
  .map((match) => match[1]);
const windowHandlers = sortedUnique([
  ...[...sources.get(SOURCE_PATHS[1]).matchAll(
    /\battribute\s+\w*EventHandler\s+(on[a-z0-9]+);/g
  )].map((match) => match[1]),
  ...WINDOW_SUPPLEMENTS
]);
const windowSet = new Set(windowHandlers);
const htmlHandlers = sortedUnique([
  ...registered.filter((name) => !windowSet.has(name)),
  ...HTML_SUPPLEMENTS
]);
for (const required of REQUIRED_CHROMIUM_HANDLERS) {
  if (!htmlHandlers.includes(required)) throw new Error(`Required handler missing: ${required}`);
}

const rendered = renderProfile(htmlHandlers, windowHandlers);
if (process.argv.includes('--check')) {
  if (await readFile(outputPath, 'utf8') !== rendered) {
    throw new Error('Browser event-handler profile is stale; run npm run handlers:update');
  }
} else {
  await writeFile(outputPath, rendered, 'utf8');
}
